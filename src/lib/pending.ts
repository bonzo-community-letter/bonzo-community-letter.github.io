/**
 * An attempt in flight, written down where a page reload cannot lose it.
 *
 * On a phone the wallet app takes the browser away to approve, and sends the
 * reader back to this page as a **fresh load** (`?wallet=return`). React state
 * does not survive that, so a dialog that only lived in memory reopens empty —
 * and, because the session is still being restored, it says "connect a wallet"
 * while the signature is already on the topic.
 *
 * The record is the one thing needed to ask the chain afterwards: the
 * transaction id was generated here, before the wallet was asked, so it is
 * known even when the wallet never answers. `sessionStorage` dies with the tab,
 * which is exactly the lifetime of a fact about one tab's attempt.
 */
import type { HederaNetwork } from './hcs'

export interface PendingSubmission {
  /** `0.0.x@seconds.nanos` — generated by this page, not by the wallet. */
  transactionId: string
  accountId: string
  topicId: string
  network: HederaNetwork
  /** Epoch ms, for the expiry below. */
  startedAt: number
}

const KEY = 'open-letter:pending-submission'

/** An attempt older than this is not worth resuming — the reader has moved on. */
export const PENDING_TTL_MS = 15 * 60_000

function storage(): Storage | null {
  try {
    return typeof sessionStorage === 'undefined' ? null : sessionStorage
  } catch {
    // Storage can be denied outright (private mode, hardened settings).
    return null
  }
}

export function savePending(record: PendingSubmission): void {
  try {
    storage()?.setItem(KEY, JSON.stringify(record))
  } catch {
    // A page that cannot write is no worse than one that never had the record.
  }
}

export function clearPending(): void {
  try {
    storage()?.removeItem(KEY)
  } catch {
    // Nothing to undo.
  }
}

/** The attempt this tab was making, if it is still recent and still this build's. */
export function readPending(network: HederaNetwork, now = Date.now()): PendingSubmission | null {
  let raw: string | null = null
  try {
    raw = storage()?.getItem(KEY) ?? null
  } catch {
    return null
  }
  if (!raw) return null

  try {
    const parsed = JSON.parse(raw) as Partial<PendingSubmission>
    const { transactionId, accountId, topicId, network: recorded, startedAt } = parsed
    if (
      typeof transactionId !== 'string' ||
      typeof accountId !== 'string' ||
      typeof topicId !== 'string' ||
      typeof startedAt !== 'number'
    ) {
      return null
    }
    // A record from the other network is not this page's business.
    if (recorded !== network) return null
    if (now - startedAt > PENDING_TTL_MS) return null
    return { transactionId, accountId, topicId, network, startedAt }
  } catch {
    return null
  }
}
